ROOT = Path(__file__).resolve().parents[2]
BASE_COLORS = {mode: values['window'] for mode, values in
               json.loads(Path(__file__).with_name('palette.json').read_text(encoding='utf-8')).items()}
PADDING = 12
RADIUS = 8
SIZE = PADDING + RADIUS
EDGES = ('top', 'bottom', 'left', 'right')
CORNERS = ('topleft', 'topright', 'bottomleft', 'bottomright')


def render(mode, active_color=None):
    if active_color is not None and not re.fullmatch(r"#[0-9A-Fa-f]{6}", active_color):
        raise ValueError("Invalid active window color")
    bg = BASE_COLORS[mode]
    active, inactive = ('#3F3F3F', '#2A2A2A') if mode == 'dark' else (
        '#E5E5E5', '#D5D5D5')
    lines = ['<svg xmlns="http://www.w3.org/2000/svg" width="144" height="240" viewBox="0 0 144 240">',
             '  <!-- Generated by scripts/theme/window-frames.py. -->',
             f'  <style id="current-color-scheme">.ColorScheme-Background {{ color: {bg}; }}</style>',
             '  <defs>']
    for name, alpha in [('active', 0.28), ('inactive', 0.16)]:
        lines += [f'    <linearGradient id="{name}-edge" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="12">',
                  f'      <stop offset="0" stop-color="#000000" stop-opacity="0"/><stop offset="0.55" stop-color="#000000" stop-opacity="{alpha*0.3:.3f}"/><stop offset="1" stop-color="#000000" stop-opacity="{alpha:.3f}"/>',
                  '    </linearGradient>',
                  f'    <radialGradient id="{name}-round" gradientUnits="userSpaceOnUse" cx="20" cy="20" r="20">',
                  f'      <stop offset="0.4" stop-color="#000000" stop-opacity="{alpha:.3f}"/><stop offset="0.67" stop-color="#000000" stop-opacity="{alpha*0.3:.3f}"/><stop offset="1" stop-color="#000000" stop-opacity="0"/>',
                  '    </radialGradient>',
                  f'    <radialGradient id="{name}-square" gradientUnits="userSpaceOnUse" cx="12" cy="12" r="12">',
                  f'      <stop offset="0" stop-color="#000000" stop-opacity="{alpha:.3f}"/><stop offset="0.45" stop-color="#000000" stop-opacity="{alpha*0.3:.3f}"/><stop offset="1" stop-color="#000000" stop-opacity="0"/>',
                  '    </radialGradient>']
    lines.append('  </defs>')
    neutral_fill = 'class="ColorScheme-Background" fill="currentColor"'
    active_fill = f'fill="{active_color}"' if active_color else neutral_fill
    for row, (prefix, border, shade) in enumerate((('decoration', active, 'active'),
                                                   ('decoration-inactive', inactive, 'inactive'))):
        fill = active_fill if row == 0 else neutral_fill
        y = 4 + row * 88
        # All four sides have equal 20 px slice dimensions: 12 px shadow
        # outside the client and 8 px inside. Only the top is rounded; a
        # decoration cannot safely clip arbitrary application content.
        edge = (f'<rect width="32" height="12" fill="url(#{shade}-edge)"/>'
                f'<rect y="12" width="32" height="8" {fill}/>'
                f'<rect y="12" width="32" height="1" fill="{border}"/>')
        top = (f'<rect width="20" height="20" fill="url(#{shade}-round)"/>'
               f'<path d="M12 20 A8 8 0 0 1 20 12 L20 20 Z" {fill}/>'
               f'<path d="M12 20 A8 8 0 0 1 20 12 L20 13 A7 7 0 0 0 13 20 Z" fill="{border}"/>')
        bottom = (f'<rect width="12" height="12" fill="url(#{shade}-square)"/>'
                  f'<rect x="12" width="8" height="12" fill="url(#{shade}-edge)"/>'
                  f'<rect width="8" height="12" transform="translate(0 20) rotate(-90)" fill="url(#{shade}-edge)"/>'
                  f'<rect x="12" y="12" width="8" height="8" {fill}/>'
                  f'<path d="M12 20 V12 H20 V13 H13 V20 Z" fill="{border}"/>')
        pieces = [('top', f'translate(24 {y})', edge),
                  ('bottom', f'translate(24 {y+72}) scale(1 -1)', edge),
                  ('left', f'translate(4 {y+52}) rotate(-90)', edge),
                  ('right', f'translate(76 {y+20}) rotate(90)', edge),
                  ('topleft', f'translate(4 {y})', top),
                  ('topright', f'translate(76 {y}) scale(-1 1)', top),
                  ('bottomleft', f'translate(4 {y+72}) scale(1 -1)', bottom),
                  ('bottomright', f'translate(76 {y+72}) scale(-1 -1)', bottom),
                  ('center', f'translate(24 {y+20})', f'<rect width="32" height="32" {fill}/>')]
        for part, transform, content in pieces:
            lines.append(f'  <g id="{prefix}-{part}" transform="{transform}">{content}</g>')
    # KWin uses this separate no-padding surface when maximized.
    for row, (prefix, border) in enumerate((('decoration-maximized', active),
                                             ('decoration-maximized-inactive', inactive))):
        fill = active_fill if row == 0 else neutral_fill
        y = 4 + row * 20
        for i, part in enumerate((*EDGES, *CORNERS, 'center')):
            attrs = fill if part == 'center' else f'fill="{border}"'
            lines.append(f'  <rect id="{prefix}-{part}" x="{88+i*4}" y="{y}" width="2" height="2" {attrs}/>')
    lines.append('</svg>')
    result = '\n'.join(lines) + '\n'
    tree = ET.fromstring(result)
    ids = [node.get('id') for node in tree.iter() if node.get('id')]
    assert len(ids) == len(set(ids))
    return result


# Sample the selected wallpaper once. This is a bounded, opaque Mica-style
# approximation, not DWM's position-dependent material or a live blur shader.

def tint_color(mode, mean):
    base = int(BASE_COLORS[mode][1:3], 16)
    weight = 0.10 if mode == "dark" else 0.06
    values = [round(base * (1 - weight) + value * weight) for value in mean]
    return "#" + "".join(f"{value:02X}" for value in values)


IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}


def configured_wallpaper(config):
    """Use a saved local image without polling or changing KDE settings.

    Global SVG themes cannot tint individual monitors separately. Prefer
    a unique saved primary-screen image; do not guess between activities.
    """
    parser = configparser.ConfigParser(interpolation=None, strict=False,
                                       delimiters=("=",))
    try:
        with config.open(encoding="utf-8") as source:
            parser.read_file(source)
        candidates = []
        for section in parser.sections():
            match = re.fullmatch(r"Containments\]\[([^\]]+)\]\[Wallpaper\]\[org\.kde\.image\]\[General", section)
            if not match:
                continue
            owner = "Containments][" + match.group(1)
            if not parser.has_section(owner):
                continue
            containment = parser[owner]
            if containment.get("wallpaperplugin") != "org.kde.image":
                continue
            if containment.get("plugin") not in ("org.kde.plasma.desktop", "org.kde.plasma.folder"):
                continue
            value = parser[section].get("Image", "").strip()
            if not value:
                continue
            if value.startswith("file:"):
                uri = urlsplit(value)
                if uri.netloc not in ("", "localhost") or uri.query or uri.fragment:
                    continue
                path = Path(unquote(uri.path))
            else:
                path = Path(value)
            if path.is_absolute() and (path.is_dir() or
                    (path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES)):
                candidates.append((containment.get("lastScreen", ""), path))
        primary = {path for screen, path in candidates if screen == "0"}
        paths = primary or {path for _, path in candidates}
        if len(paths) == 1:
            return next(iter(paths))
    except (OSError, ValueError, configparser.Error) as error:
        print(f"Saved wallpaper unavailable: {error}", file=sys.stderr)
    return None


def wallpaper_sources(package):
    """Choose one source per mode; an actual loaded file is shared."""
    sources = dict.fromkeys(BASE_COLORS)
    if package is None:
        return sources
    if package.is_file():
        return dict.fromkeys(BASE_COLORS, package)
    for mode in sources:
        folders = ("images_dark", "images") if mode == "dark" else ("images",)
        for name in folders:
            directory = package / "contents" / name
            if not directory.is_dir():
                continue
            images = sorted(p for p in directory.iterdir()
                            if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES)
            if images:
                sources[mode] = images[-1]
                break
    return sources


def sample_wallpaper(path, decode):
    # Share the bounded still-image/ICC decoder with automatic accent.
    # The alpha-weighted mean is only the static material approximation,
    # not the Windows accent extractor or a measured DWM material formula.
    try:
        _, _, pixels = decode(path)
        red = green = blue = weight = 0
        for b, g, r, a in zip(pixels[0::4], pixels[1::4], pixels[2::4], pixels[3::4]):
            red += r * a
            green += g * a
            blue += b * a
            weight += a
        return (red / weight, green / weight, blue / weight) if weight else None
    except (OSError, ValueError) as error:
        print(f"Wallpaper tint unavailable: {error}", file=sys.stderr)
        return None


def wallpaper_tints(package, sync=None):
    if sync is None:
        sync = runpy.run_path(str(Path(__file__).with_name("sync-accent.py")))
    sources = wallpaper_sources(package)
    identity = sync["wallpaper_file_identity"]
    # Capture all identities before any decode and reuse one sample for
    # both variants when they select the same file.
    fingerprints = {path: identity(path) for path in set(sources.values()) if path is not None}
    samples = {path: sample_wallpaper(path, sync["decode_wallpaper_bitmap"])
               for path in fingerprints}

    def validate():
        if wallpaper_sources(package) != sources or any(
                identity(path) != fingerprint for path, fingerprint in fingerprints.items()):
            raise ValueError("Wallpaper changed while preparing window materials")

    validate()
    colors = {mode: tint_color(mode, samples[path]) if samples.get(path) is not None else None
              for mode, path in sources.items()}
    return colors, validate


def patch_window_svg(svg, active, inactive):
    # Keep the existing Kvantum artwork and every non-window role intact.
    # The two window paths already implement active/inactive state selection.
    for element, color in (("window-normal", active), ("window-normal-inactive", inactive)):
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", color):
            raise ValueError("Invalid window fill")
        pattern = rf'<path\b[^>]*\bid="{element}"[^>]*/>'

        def replace(match):
            path = match.group(0)
            path, fills = re.subn(r'\bfill="[^"]*"', f'fill="{color}"', path)
            path, opacities = re.subn(r'\bopacity="[^"]*"', 'opacity="1"', path)
            if fills != 1 or opacities != 1:
                raise ValueError("Unexpected Kvantum window element: " + element)
            return path

        svg, count = re.subn(pattern, replace, svg)
        if count != 1:
            raise ValueError("Missing or duplicate Kvantum window element: " + element)
    # Toolbars use the menubar slice set. Match only the first filled rect
    # in each role; never recolor the transparent border/overlay artwork.
    # The window and toolbar now share a single opaque wallpaper tint.
    if 'id="menubar-normal"' in svg:
        for prefix, color in (("menubar-normal", active),
                              ("menubar-normal-inactive", inactive)):
            for part in ("", "-left", "-right", "-top", "-topleft", "-topright",
                         "-bottom", "-bottomleft", "-bottomright"):
                role = prefix + part
                if part.startswith("-bottom"):
                    pattern = rf'(<g\b[^>]*\bid="{role}"[^>]*>\s*<rect\b[^>]*\bfill=")[^"]+(")'
                else:
                    pattern = rf'(<rect\b[^>]*\bid="{role}"[^>]*\bfill=")[^"]+(")'
                svg, count = re.subn(pattern, lambda match: match[1] + color + match[2], svg)
                if count != 1:
                    raise ValueError("Unexpected or missing Kvantum toolbar element: " + role)
    ET.fromstring(svg)
    return svg


def plan_local(aurorae_dir, kvantum_dir, colors, owned_file):
    # The same Kvantum SVG carries the accent and material bindings.
    # Reject externally managed paths and stage all outputs before writing.
    pending = {}
    for directory in (aurorae_dir, kvantum_dir):
        if directory.is_symlink() or directory.parent.is_symlink():
            raise ValueError(f"Refusing externally managed theme directory: {directory}")
    for mode, base in BASE_COLORS.items():
        active = colors[mode]
        decoration = aurorae_dir / f"windows-modern-{mode}-aurorae" / "decoration.svg"
        kvantum = kvantum_dir / ("Windows-modernDark.svg" if mode == "dark" else "Windows-modern.svg")
        if decoration.parent.is_symlink():
            raise ValueError(f"Refusing externally managed decoration: {decoration.parent}")
        if decoration.exists() or decoration.is_symlink():
            old = owned_file(decoration).read_bytes()
            # Only replace our generated frame. Recognize either the
            # pristine neutral frame or an exact prior static-tint output.
            if old != render(mode).encode("utf-8"):
                node = ET.fromstring(old).find(".//*[@id='decoration-center']")
                fill = node[0].get("fill") if node is not None and len(node) else None
                if not fill or not re.fullmatch(r"#[0-9A-Fa-f]{6}", fill) or old != render(mode, fill).encode("utf-8"):
                    raise ValueError(f"Decoration differs from the generated window frame: {decoration}")
            new = render(mode, active).encode("utf-8")
            if old != new:
                pending[decoration] = (old, new)
        if kvantum.exists() or kvantum.is_symlink():
            old = owned_file(kvantum).read_bytes()
            new = patch_window_svg(old.decode("utf-8"), active or base, base).encode("utf-8")
            if old != new:
                pending[kvantum] = (old, new)
    return pending


def plan_transparency(kvantum_dir, plasma_dir, popup_source, enabled, owned_file):
    """Stage only the owned transparency keys and native frame selectors."""
    pending = {}
    opaque = ("translucent_windows", "transparent_dolphin_view",
              "transparent_pcmanfm_sidepane", "transparent_pcmanfm_view")
    blur = ("blurring", "popup_blurring", "blur_translucent")
    for mode, name in (("dark", "Windows-modernDark"), ("light", "Windows-modern")):
        config = owned_file(kvantum_dir / (name + ".kvconfig"))
        old = config.read_bytes()
        new = old.decode("utf-8")
        for key in opaque + blur:
            value = "true" if enabled and key in blur else "false"
            new, count = re.subn(r"(?m)^" + key + r"=(?:true|false)(?=\r?$)", key + "=" + value, new)
            if count != 1:
                raise ValueError(f"Missing or duplicate Kvantum transparency key {key}: {config}")
        if old != new.encode("utf-8"):
            pending[config] = (old, new.encode("utf-8"))
        theme = plasma_dir / ("Windows-modern-" + mode)
        source = popup_source / theme.name
        for variant in ("", "translucent"):
            for role in ("dialogs/background.svg", "widgets/panel-background.svg"):
                target = theme / variant / role
                # These are exact generated selectors, not arbitrary SVGs.
                # Refuse externally managed ancestors before reading/writing.
                for parent in (target.parent, target.parent.parent, theme, plasma_dir, plasma_dir.parent):
                    if parent.is_symlink():
                        raise ValueError(f"Refusing externally managed popup directory: {parent}")
                old = owned_file(target).read_bytes()
                normal = (source / variant / role).read_bytes()
                solid = (source / "solid" / role).read_bytes()
                if old not in (normal, solid):
                    raise ValueError(f"Popup frame differs from the generated selector: {target}")
                new = normal if enabled else solid
                ET.fromstring(new)
                if old != new:
                    pending[target] = (old, new)
    return pending


def read_transparency_marker(path):
    if any(parent.is_symlink() for parent in (path, path.parent, path.parent.parent)):
        raise ValueError("Refusing externally managed transparency state")
    if not path.exists():
        return None
    if not path.is_file() or path.stat().st_uid != os.getuid():
        raise ValueError("Invalid or externally owned transparency state")
    data = path.read_bytes()
    if not re.fullmatch(rb"blurEnabled=(true|false)?\n?", data):
        raise ValueError("Invalid saved blur preference")
    return data


def read_blur_preference():
    config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    path = config / "kwinrc"
    if config.is_symlink() or path.is_symlink() or (path.exists() and (
            not path.is_file() or path.stat().st_uid != os.getuid())):
        raise ValueError("Refusing externally managed KWin configuration")
    value = subprocess.check_output(
        ["kreadconfig6", "--file", "kwinrc", "--group", "Plugins", "--key", "blurEnabled"],
        text=True).rstrip("\n")
    if value not in ("", "true", "false"):
        raise ValueError("Invalid blur preference")
    return value


def write_blur_preference(expected, desired):
    if read_blur_preference() != expected:
        raise ValueError("KWin blur preference changed during transparency update")
    if expected == desired:
        return
    command = ["kwriteconfig6", "--notify", "--file", "kwinrc", "--group", "Plugins", "--key", "blurEnabled"]
    subprocess.run(command + ([desired] if desired else ["--delete"]), check=True)
    if read_blur_preference() != desired:
        raise ValueError("KWin blur preference was not saved")


def write_transparency_marker(path, expected, desired):
    if read_transparency_marker(path) != expected:
        raise ValueError("Transparency marker changed during update")
    if expected == desired:
        return
    if desired is None:
        path.unlink()
        return
    # The only creation path starts with no marker. Publish complete bytes
    # without overwriting a marker created by another writer.
    if expected is not None:
        raise ValueError("Refusing to replace an existing transparency marker")
    path.parent.mkdir(parents=True, exist_ok=True)
    if read_transparency_marker(path) is not None:
        raise ValueError("Transparency marker appeared during update")
    with tempfile.NamedTemporaryFile(prefix=".wm-transparency-", dir=path.parent) as temp:
        temp.write(desired)
        temp.flush()
        os.link(temp.name, path)


class TransparencyPreference:
    """Stage the saved blur choice and marker alongside the renderer files."""

    def __init__(self, path, enabled):
        self.path = path
        self.marker = read_transparency_marker(path)
        self.blur = read_blur_preference()
        if enabled:
            if self.marker is None:
                raise ValueError("No saved transparency-off state")
            self.target_marker = None
            self.target_blur = self.marker.decode("ascii").strip().split("=", 1)[1]
        else:
            self.target_marker = self.marker if self.marker is not None else (
                "blurEnabled=" + self.blur + "\n").encode("ascii")
            self.target_blur = "false"
        self.blur_attempted = False
        self.marker_attempted = False

    def validate(self):
        if read_transparency_marker(self.path) != self.marker or read_blur_preference() != self.blur:
            raise ValueError("Transparency preference changed during update")

    def apply(self):
        self.validate()
        self.blur_attempted = self.blur != self.target_blur
        write_blur_preference(self.blur, self.target_blur)
        self.marker_attempted = self.marker != self.target_marker
        write_transparency_marker(self.path, self.marker, self.target_marker)
        if (read_transparency_marker(self.path) != self.target_marker
                or read_blur_preference() != self.target_blur):
            raise ValueError("Transparency preference changed after update")

    def rollback(self):
        # A failed command may already have written the new value. Restore
        # only our own target, leaving an unrelated external change intact.
        failures = []
        for attempted, reader, writer, before, after in (
                (self.marker_attempted, lambda: read_transparency_marker(self.path),
                 lambda old, new: write_transparency_marker(self.path, old, new),
                 self.marker, self.target_marker),
                (self.blur_attempted, read_blur_preference, write_blur_preference,
                 self.blur, self.target_blur)):
            if not attempted:
                continue
            try:
                current = reader()
                if current == after:
                    writer(after, before)
                elif current != before:
                    raise ValueError("Transparency preference changed during rollback")
            except (OSError, ValueError, subprocess.SubprocessError) as error:
                failures.append(str(error))
        if failures:
            raise ValueError("; ".join(failures))


MATERIAL_SAMPLE_REVISION = 1
MATERIAL_GROUP = "WindowsModernMaterial"
MATERIAL_KEY = "Sample"


def live_material_enabled(mode, control):
    """Only synchronize the selected, user-installed Windows Modern renderers."""
    config, data = control["CONFIG"], control["DATA"]
    markers = (data / "windows-modern/transparency-off",
               Path.home() / ".local/share/windows-modern/transparency-off")
    if any(path.exists() or path.is_symlink() for path in markers):
        return False
    if not control["active_mode"](mode):
        return False
    style = "kvantum-dark" if mode == "dark" else "kvantum"
    if control["read"]("KDE", "widgetStyle") != style:
        return False

    def setting(file, group, key):
        return subprocess.check_output(
            ["kreadconfig6", "--file", file, "--group", group, "--key", key],
            text=True).rstrip("\n")

    return (setting("Kvantum/kvantum.kvconfig", "General", "theme") == "Windows-modern"
            and setting("kwinrc", "org.kde.kdecoration2", "library") == "org.kde.kwin.aurorae"
            and setting("kwinrc", "org.kde.kdecoration2", "theme")
            == f"__aurorae__svg__windows-modern-{mode}-aurorae")


def live_material_state(snapshot, raw, sync):
    """Cache only the global renderer's primary-screen sample, not its SVGs."""
    primary = dict(snapshot["wallpapers"][0])
    source = {"schema_version": 1, "analysis_revision": sync["WALLPAPER_ANALYSIS_REVISION"],
              "material_revision": MATERIAL_SAMPLE_REVISION, "base_colors": dict(BASE_COLORS),
              "wallpapers": [primary]}
    try:
        previous = json.loads(raw) if raw is not None else None
    except (ValueError, TypeError):
        previous = None
    if isinstance(previous, dict) and all(previous.get(key) == value for key, value in source.items()):
        colors = previous.get("colors")
        if (isinstance(colors, dict) and set(colors) == set(BASE_COLORS)
                and all(isinstance(color, str) and re.fullmatch(r"#[0-9A-Fa-f]{6}", color)
                        for color in colors.values())):
            return {**source, "colors": colors}
    mean = sample_wallpaper(Path(primary["path"]), sync["decode_wallpaper_bitmap"])
    if mean is None:
        return None
    return {**source, "colors": {mode: tint_color(mode, mean) for mode in BASE_COLORS}}


def write_material_state(value):
    args = ["kwriteconfig6", "--notify", "--file", "kdeglobals",
            "--group", MATERIAL_GROUP, "--key", MATERIAL_KEY]
    subprocess.run(args + (["--delete"] if value is None else [value]), check=True)


def sync_live_material(mode, control):
    # The caller holds the same lock as accent synchronization and explicit
    # transparency operations. Do not sample previews or change KWin settings.
    if not live_material_enabled(mode, control):
        return "skipped"
    config, data, sync = control["CONFIG"], control["DATA"], control["SYNC"]
    aurorae = data / "aurorae/themes"
    kvantum = config / "Kvantum/Windows-modern"
    required = [aurorae / f"windows-modern-{name}-aurorae" / "decoration.svg" for name in BASE_COLORS]
    required += [kvantum / name for name in ("Windows-modern.svg", "Windows-modernDark.svg")]
    if not all(path.is_file() for path in required):
        return "skipped"
    if config.is_symlink():
        raise ValueError("Refusing externally managed KDE configuration")
    sync["owned_file"](config / "kdeglobals")
    changed_error = control["WallpaperChangedError"]
    try:
        snapshot = control["discover_wallpapers"](primary_only=True)
    except changed_error:
        raise
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError):
        # An unsettled/unsupported desktop is not evidence for a new tint.
        # Keep the last material and wait for the next native event.
        return "retained"

    read = control["read"]
    raw = read(MATERIAL_GROUP, MATERIAL_KEY)
    state = live_material_state(snapshot, raw, sync)
    if state is None:
        # A decode failure after accepting a snapshot must not hide a
        # replacement race. Stable unsupported images retain the old tint.
        control["require_wallpaper_snapshot"](snapshot, primary_only=True)
        return "retained"
    desired = json.dumps(state, separators=(",", ":"), sort_keys=True)
    pending = plan_local(aurorae, kvantum, state["colors"], sync["owned_file"])

    def validate():
        control["require_wallpaper_snapshot"](snapshot, primary_only=True)
        if not live_material_enabled(mode, control) or read(MATERIAL_GROUP, MATERIAL_KEY) != raw:
            raise ValueError("Appearance changed during material synchronization")

    # Re-plan on cache hits: upgrades and accent changes can replace SVGs
    # even when the wallpaper itself is unchanged.
    validate()
    if not pending and desired == raw:
        return "unchanged"
    written = sync["write_pending"](pending)
    state_write_attempted = False
    try:
        validate()
        if desired != raw:
            state_write_attempted = True
            write_material_state(desired)
            if read(MATERIAL_GROUP, MATERIAL_KEY) != desired:
                raise ValueError("Window material sample was not saved")
    except Exception:
        try:
            sync["restore_pending"](pending, written)
        except (OSError, ValueError) as error:
            print(f"Material asset rollback incomplete: {error}", file=sys.stderr)
        if state_write_attempted:
            try:
                if read(MATERIAL_GROUP, MATERIAL_KEY) == desired:
                    write_material_state(raw)
            except (OSError, ValueError, subprocess.SubprocessError) as error:
                print(f"Material sample rollback incomplete: {error}", file=sys.stderr)
        raise
    return "changed" if pending else "unchanged"


def apply_local(aurorae_dir, kvantum_dir, package=None, validate_selection=None,
                transparency=None, transparency_state=None):
    # Reuse the accent writer's optimistic ownership/byte checks, atomic
    # replacement and conditional rollback. The shell caller holds the
    # existing appearance lock. No independently edited lines are lost.
    sync = runpy.run_path(str(Path(__file__).with_name("sync-accent.py")))
    if (transparency is None) != (transparency_state is None):
        raise ValueError("Explicit transparency requires its saved preference path")
    preference = (TransparencyPreference(transparency_state, transparency[2])
                  if transparency is not None else None)
    colors, validate_files = wallpaper_tints(package, sync)
    if transparency is not None:
        # Explicit toggles must not silently update only a subset of an
        # incomplete installation. Partial installs retain the old helper.
        for mode, name in (("dark", "Windows-modernDark"), ("light", "Windows-modern")):
            sync["owned_file"](aurorae_dir / f"windows-modern-{mode}-aurorae" / "decoration.svg")
            sync["owned_file"](kvantum_dir / (name + ".svg"))
    pending = plan_local(aurorae_dir, kvantum_dir, colors, sync["owned_file"])
    if transparency is not None:
        plasma_dir, popup_source, enabled = transparency
        pending.update(plan_transparency(kvantum_dir, plasma_dir, popup_source,
                                         enabled, sync["owned_file"]))

    def validate():
        validate_files()
        if validate_selection is not None:
            validate_selection()

    validate()
    if preference is not None:
        preference.validate()
    written = sync["write_pending"](pending)
    try:
        validate()
        if preference is not None:
            preference.apply()
            validate()
    except Exception:
        if preference is not None:
            try:
                preference.rollback()
            except (OSError, ValueError, subprocess.SubprocessError) as error:
                print(f"Transparency preference rollback incomplete: {error}", file=sys.stderr)
        try:
            sync["restore_pending"](pending, written)
        except (OSError, ValueError) as error:
            print(f"Window material rollback incomplete: {error}", file=sys.stderr)
        raise
    print(f"Window material update: {len(pending)} file(s) changed.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--check', action='store_true')
    action.add_argument('--apply-local', action='store_true')
    action.add_argument('--sync-live', choices=('dark', 'light'),
                        help='Refresh the installed static material from the settled desktop')
    parser.add_argument('--directory', type=Path, help='Complete staged Aurorae packages')
    parser.add_argument('--aurorae-dir', type=Path)
    parser.add_argument('--kvantum-dir', type=Path)
    parser.add_argument('--plasma-dir', type=Path)
    parser.add_argument('--popup-source', type=Path)
    parser.add_argument('--transparency', choices=('on', 'off'))
    parser.add_argument('--transparency-state', type=Path)
    wallpaper = parser.add_mutually_exclusive_group()
    wallpaper.add_argument('--wallpaper-package', type=Path)
    wallpaper.add_argument('--wallpaper-config', type=Path)
    wallpaper.add_argument('--wallpaper-live', action='store_true',
                           help='Use the settled screen 0 image from the native tray bridge')
    args = parser.parse_args()
    if args.sync_live:
        if os.geteuid() == 0 or any((args.directory, args.aurorae_dir, args.kvantum_dir,
                                    args.plasma_dir, args.popup_source, args.transparency,
                                    args.transparency_state, args.wallpaper_package, args.wallpaper_config, args.wallpaper_live)):
            parser.error("--sync-live requires a normal desktop user and no other asset arguments")
        control = runpy.run_path(str(Path(__file__).with_name("accent-control.py")))
        try:
            print(sync_live_material(args.sync_live, control))
        except control["WallpaperChangedError"] as error:
            parser.exit(75, f"Window material synchronization: {error}\n")
        except (OSError, ValueError, KeyError, TypeError, ET.ParseError, subprocess.SubprocessError) as error:
            parser.exit(1, f"Window material synchronization: {error}\n")
        return
    transparency = None
    if any((args.plasma_dir, args.popup_source, args.transparency, args.transparency_state)):
        if not args.apply_local or not all((args.plasma_dir, args.popup_source, args.transparency, args.transparency_state)):
            parser.error("Transparency requires --apply-local, --plasma-dir, --popup-source and --transparency-state")
        if args.transparency == "off" and any((args.wallpaper_package, args.wallpaper_config, args.wallpaper_live)):
            parser.error("Transparency off uses neutral window bases")
        transparency = (args.plasma_dir, args.popup_source, args.transparency == "on")
    if args.apply_local:
        if args.directory:
            parser.error('--directory cannot be used with --apply-local')
        if os.geteuid() == 0 or not args.aurorae_dir or not args.kvantum_dir:
            parser.error('--apply-local requires a normal user and both installed theme paths')
        try:
            selected = (configured_wallpaper(args.wallpaper_config)
                        if args.wallpaper_config else args.wallpaper_package)
            validate_selection = None
            if args.wallpaper_config:
                def validate_selection():
                    if configured_wallpaper(args.wallpaper_config) != selected:
                        raise ValueError("Saved wallpaper changed while preparing window materials")
            if args.wallpaper_live:
                # The same native snapshot supplies the automatic accent.
                # Do not fall back to stale saved settings during a preview,
                # crossfade or activity change. A global SVG cannot be
                # different on each screen; use the existing screen-0 policy.
                control = runpy.run_path(str(Path(__file__).with_name("accent-control.py")))
                snapshot = control["discover_wallpapers"](primary_only=True)
                selected = Path(snapshot["wallpapers"][0]["path"])
                validate_selection = lambda: control["require_wallpaper_snapshot"](snapshot, primary_only=True)
            if args.wallpaper_config and selected is None:
                print("No unambiguous local image wallpaper; using neutral window bases.")
            apply_local(args.aurorae_dir, args.kvantum_dir, selected, validate_selection,
                        transparency, args.transparency_state)
        except (OSError, ValueError, KeyError, TypeError, ET.ParseError, subprocess.SubprocessError) as error:
            parser.exit(1, f"Window material update: {error}\n")
        return
    if args.aurorae_dir or args.kvantum_dir or args.wallpaper_package or args.wallpaper_config or args.wallpaper_live:
        parser.error('Installed theme arguments require --apply-local')
    directory = args.directory or ROOT / 'aurorae'
    modes = ('dark', 'light') if args.directory else ('dark',)
    for mode in modes:
        path = directory / f'windows-modern-{mode}-aurorae' / 'decoration.svg'
        expected = render(mode)
        if args.check:
            if path.read_text(encoding='utf-8') != expected:
                parser.exit(1, f'Stale window frame: {path}\n')
        else:
            path.write_text(expected, encoding='utf-8')
    print('Aurorae ' + '/'.join(modes) + ' window frames consistent.')


if __name__ == '__main__':
    main()
